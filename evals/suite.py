"""suite.json -> evals/activation/<case>/case.yaml, for `claude plugin eval`.

The suite is Le Conseil's use-case catalogue in executable form: each case is
a situation in the Operator's register, the members whose gate it meets
(required), the members who may also sit without being wrong (allowed), and
the members it must not wake (forbidden). Everyone else who convenes is
theatre - not a failure the runner scores, but the count evals/analyze.py
reports.

suite.json is the single source. The case files are generated so the
expectations the runner grades and the expectations the analysis reads can
never drift apart, and `--check` (run by evals/test_suite.py in CI) fails when
a case file no longer matches it - the same contract bin/atlas-skills keeps
with the subroutines.

Every grader is `tool_used: Skill`, deterministic, matched against the Skill
call's input. No grader asks a model whether a member convened.

    python3 evals/suite.py           write the case files
    python3 evals/suite.py --check   exit 1 if any is stale or missing
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parent
ROOT = EVALS.parent
SUITE = EVALS / "suite.json"
CASES = EVALS / "activation"
HEADER = "# GENERATED by evals/suite.py from evals/suite.json. Do not edit this file.\n"

# Seats a case may name. The displays and the housekeeping skill are not
# members, and Le Sceptique is standing: he may sit on any case, so he is
# never required, allowed, or forbidden - only counted.
NOT_MEMBERS = {"le-cadran", "le-conseil"}
STANDING = "le-sceptique"
STRICT = "le-fripon"
KINDS = ("positive", "negative", "multi", "named")


def members() -> list[str]:
    return sorted(p.parent.name for p in ROOT.glob("skills/le-*/SKILL.md")
                  if p.parent.name not in NOT_MEMBERS)


def load() -> dict:
    return json.loads(SUITE.read_text(encoding="utf-8"))


def skill_match(member: str) -> str:
    # The Skill call's input as the runner sees it, e.g.
    # {"skill":"atlas:le-vigile","args":"..."}. Anchored on the skill key and
    # the closing quote, so le-vigile in a reason does not count as a call.
    return rf'"skill":\s*"(atlas:)?{member}"'


def forbidden_of(case: dict, ring: list[str]) -> list[str]:
    """Explicit forbidden members, '*' expanded, and Le Fripon unless required.

    Le Fripon is held on every case that does not arm him by name. That is
    the strict seat's whole contract, so no case has to remember to say it.
    """
    seated = set(case["required"]) | set(case["allowed"]) | {STANDING}
    out = []
    for m in case.get("forbidden", []):
        if m == "*":
            out.extend(x for x in ring if x not in seated)
        else:
            out.append(m)
    if STRICT not in case["required"]:
        out.append(STRICT)
    return sorted(set(out))


def validate(suite: dict, ring: list[str]) -> list[str]:
    errors, seen = [], set()
    for c in suite["cases"]:
        name = c["name"]
        if name in seen:
            errors.append(f"{name}: duplicate case name")
        seen.add(name)
        if c["kind"] not in KINDS:
            errors.append(f"{name}: kind {c['kind']!r} is not one of {KINDS}")
        named = c["required"] + c["allowed"] + [m for m in c.get("forbidden", []) if m != "*"]
        for m in named:
            if m not in ring:
                errors.append(f"{name}: {m} is not a member skill")
            if m == STANDING:
                errors.append(f"{name}: {STANDING} is standing; leave him out")
        overlap = set(c["required"]) & set(forbidden_of(c, ring))
        if overlap:
            errors.append(f"{name}: both required and forbidden: {sorted(overlap)}")
        if c["kind"] == "negative" and c["required"]:
            errors.append(f"{name}: a negative case requires no one")
        if c["kind"] != "negative" and not c["required"]:
            errors.append(f"{name}: a {c['kind']} case must require someone")
    return errors


def q(text: str) -> str:
    """A YAML double-quoted scalar. JSON's escapes are a subset of YAML's."""
    return json.dumps(text, ensure_ascii=False)


def grader(name: str, member: str, *, least: int, most: int | None) -> list[str]:
    lines = [
        "  - type: tool_used",
        f"    name: {q(name)}",
        "    tool: Skill",
        # Single-quoted: YAML keeps the backslash in \s literally.
        f"    input_match: '{skill_match(member)}'",
        f"    min: {least}",
    ]
    if most is not None:
        lines.append(f"    max: {most}")
    return lines


def render(case: dict, defaults: dict, ring: list[str]) -> str:
    tools = ", ".join(defaults["allowed_tools"])
    out = [
        'schema_version: "1.0"',
        f"name: {q(case['name'])}",
        f"description: {q(case['gate'])}",
        f"tags: [{case['kind']}, {case['source']}]",
        "execution:",
        f"  prompt: {q(case['prompt'])}",
        f"  max_turns: {defaults['max_turns']}",
        f"  timeout_seconds: {defaults['timeout_seconds']}",
        f"  allowed_tools: [{tools}]",
        f"runs: {defaults['runs']}",
        "graders:",
    ]
    for m in case["required"]:
        out += grader(f"convenes {m}", m, least=1, most=None)
    for m in forbidden_of(case, ring):
        out += grader(f"holds {m}", m, least=0, most=0)
    return HEADER + "\n".join(out) + "\n"


def expected() -> dict[Path, str]:
    suite, ring = load(), members()
    errors = validate(suite, ring)
    if errors:
        raise SystemExit("evals/suite.json:\n  " + "\n  ".join(errors))
    return {CASES / c["name"] / "case.yaml": render(c, suite["defaults"], ring)
            for c in suite["cases"]}


def stale(want: dict[Path, str]) -> list[str]:
    problems = [f"{p.relative_to(ROOT)} is missing or stale" for p, text in want.items()
                if not p.exists() or p.read_text(encoding="utf-8") != text]
    problems += [f"{p.relative_to(ROOT)} has no case in suite.json"
                 for p in CASES.glob("*/case.yaml") if p not in want]
    return problems


def main(argv: list[str]) -> int:
    want = expected()
    if "--check" in argv:
        problems = stale(want)
        for p in problems:
            print(f"evals/suite.py: {p}", file=sys.stderr)
        if problems:
            print("evals/suite.py: regenerate with python3 evals/suite.py", file=sys.stderr)
            return 1
        print(f"evals/suite.py: {len(want)} case files match suite.json")
        return 0
    for p in CASES.glob("*/case.yaml"):
        if p not in want:
            p.unlink()
            p.parent.rmdir()
    for p, text in want.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"evals/suite.py: wrote {len(want)} case files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
